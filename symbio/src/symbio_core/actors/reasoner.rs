//! prompt 的**唯一渲染点**（D-048a）：事件切片 → 转写投影 → **消息数组**。
//!
//! 生成主体（`pattern = Reasoner` 的形态，[DE-001-核心架构](../../../../docs/003-design/001-核心架构.md "DE-001-核心架构") §4）的生成路径按
//! [DE-001-核心架构](../../../../docs/003-design/001-核心架构.md "DE-001-核心架构") 的「迁 C 层」归到 `plugins/session/turn_runner`——
//! `turn_runner.rs` 头注释写着「`actors` 的生成**不再走**」，生产侧调的是
//! `llm.generate_turn(...)`。本模块只留**确实有人调**的渲染入口（下方那个自由函数，
//! `turn_runner.rs` 的基线就取自它）。
//!
//! 主体连同 `reply` / `reply_timed` / `reply_streaming` 三条入口已删除：它们**没有
//! 生产调用方**，只被测试引用着。注释证明不了需求——意图会变，变了而没留痕时，代码
//! 就成了唯一还在宣称「这里有一条路」的东西。过程记在 -清单归属字段与汇总页登记 旁支二。

use crate::symbio_core::Event;

/// prompt 的**结构化渲染入口**：事件切片 → 消息数组。
///
/// 渲染本身是**纯投影**（不碰任何主体状态），缝只在「什么时候渲染、往基线上追加什么」
/// 由写方决定、「怎么把事件变成消息」由本域决定。
///
/// 生产侧（下沉后的 `plugins/session/turn_runner`）只准调本函数，**不得在定义域之外
/// 提及主体类型**——`scripts/no-direct-call-audit.mjs` 的 NDC-001：提及即可持有、
/// 持有即可直连（协作只走事件是 I1 的直接推论）。与 `recalled_event` 同一形态
/// （生产侧驱动运行器而不逐个持有主体）。
///
/// ## 结构化是唯一出口
///
/// prompt 从**转写投影**出（多轮带历史）——历史来自同一份事实源，不另存副本
/// （D-044 同族纪律）。**拍成一段文本**会把 `role: tool` 降级成散文里的纯文本，
/// 模型就看不到「这是工具结果」、也拿不到 `tool_call_id`——那是已判定的退步，
/// 不是排版偏好。
///
/// ## 为什么运行器仍要就地追加工具交换
///
/// 投影读的是**已落格**的事实（设计文档-工具轮v2化实施方案 起，跨轮的工具结果
/// 也在其中）；而**本轮**刚发生的工具交换，快照取在它落格**之前**
/// （`run_with_tools` 先取 `base_messages`、再逐轮追加），投影里当然没有。
/// 所以运行器把这一轮的交换就地累积成 `exchange` 追加到基线上——**一条基线 +
/// 就地累积**，而不是两条渲染路径。续写轮同理：恢复产生的交换也先落格再追加。
pub fn render_messages(events: &[Event]) -> Vec<crate::symbio_core::PromptMessage> {
    // `read_all` 说的是**口径**（as-of 一切已发生、不设扫描窗口），不是作用域：
    // 进来的切片已由 `turn_runner/facts.rs` 过读侧闸并按轮开窗，那一层归它定。
    crate::symbio_core::transcript()
        .read_all(events)
        .value
        .to_messages()
}
