//! Heartbeat 插件 —— 会话空闲后的**自主开轮调度**
//!
//! ## 它是什么
//!
//! 「会话空闲达到间隔之后，自动把一条提示词交进这个会话的收件箱」。本插件只回答
//! 「**什么时候**该开一轮」：间隔、按会话 id 的确定性错峰、空闲基线、常驻扫描循环，
//! 加上这一设置的两个入口（模型侧工具 + 会话选项栏那一行）。
//!
//! 「这次开轮是系统自己发起的」在事实源里的样子（触发 / 自检 / 欲 / 闸门四格）与
//! 运行参数的推导**不在本插件**：那是会话存储所有者的写窗口纪律，住在
//! `plugins/session/transcript/autonomous.rs`，经收件箱写臂进入（归属裁决见
//! [D-076](README.md#d-076-心跳片的八个宿主触点逐条落位调度随片走触发事实落进收件箱写臂 "symbio/src/plugins/heartbeat/README")）。
//!
//! ## 为什么是一个独立插件（而不是 session 里的一个模块）
//!
//! 判据是 [D-077](README.md#d-077-心跳片的落点定为一层的插件目录卸载单位与第二个消费单位都由它给出 "symbio/src/plugins/heartbeat/README") 裁决一的三条，缺一都不成立：
//!
//! 1. **卸载单位**：能被运行期停用的东西才谈得上「可独立卸载」，而容器注册表的启停动词
//!    只认**一层插件目录**；住在 `plugins/session/heartbeat/` 的那半没有可停用的单位。
//! 2. **第二个消费单位**：写标记的一方（本插件）与识别标记的一方（会话写臂）分属两个
//!    插件，`meta.trigger` 这套词汇才是**共享**词汇，它的单点定义才住在 core。
//! 3. **分形**：清单里逐项进每一棵子树，故每个智能体各有一条自己的调度循环——与切片前
//!    「每个 `SessionPlugin` 实例各跑一条」数量相等。
//!
//! ## 它对世界只说三句话，全部走地址面
//!
//! | 一句 | 地址 | 用途 |
//! |---|---|---|
//! | 读清单 | `vdfs/list(session)` | 会话的 `status` / `updated_at` / `metadata`（含 `heartbeat` 子对象） |
//! | 开一轮 | `vdfs/write(session/<id>/inbox)` | 写体带 `meta.trigger` 声明，落格与入队由会话侧完成 |
//! | 存设置 | `vdfs/write(session/<id>)` | `metadata.heartbeat` 整块替换（浅合并按键） |
//!
//! 它不持有会话插件实例，不认识事实源，也不认识会话的运行时状态表（E-007 / E-009）。
//!
//! ## 域内分工
//!
//! | 文件 | 职责 |
//! |---|---|
//! | [`plugin`] | 插件本体：能力行贡献（Tool + Option 两行）、常驻循环的启动与停机 |
//! | [`scheduler`] | 扫描循环：tick、错峰、空闲基线、触发一次写入 |
//! | [`setting`] | `Session.metadata.heartbeat` 那块数据的形状（本片写、会话侧透传） |
//! | [`tool`] | 模型侧设置入口（`heartbeat` 工具：set / get / cancel） |
//! | [`option`] | 会话选项栏那一行的声明（字段 + 子表单定义） |

