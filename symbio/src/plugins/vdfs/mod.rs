//! VDFS 插件 —— **文件系统本身**（对前端 / 对 LLM 的唯一出入口）
//!
//! 见 `docs/design/vdfs.md`。本插件的全部职责就是两件事：
//!
//! 1. 给**前端**提供调用后端文件系统的接口（`vdfs/*`）；
//! 2. 给**大模型**提供访问文件系统的工具（`vdfs_*`）。
//!
//! 两者共用同一个 [`fs::UnifiedFs`]（同一条地址规则、同一份分发），
//! 不存在第二套实现。
//!
//! ## 一棵树的两半（[`fs`]）
//!
//! ```text
//! .vdfs            根目录（系统资源清单）       ─┐
//! .vdfs/<子目录>/…  某插件子树                    ├─▶ 虚拟层 = 容器注册的根
//!                                                 ─┘
//! README.md        工作目录相对地址              ─┐
//! src/main.rs      同上                            ├─▶ 物理层 = 磁盘真实文件（[`physical`]）
//! D:/tmp/a.txt     绝对路径                        ─┘
//! ```
//!
//! 判别只有一条：**规范化后的地址是否以 `.vdfs` 打头**。除此之外本插件不持有
//! 任何拓扑知识——`.vdfs` 下有多少子目录、叫什么，由容器与各 provider 的注册决定，
//! 新增一类资源不需要改动本插件任何一行。
//!
//! ## 与其他层的分工
//!
//! - 纯接口（trait + 域类型）：`symbio_core::vdfs_provider`
//! - symbio 桥（上下文注入 / 错误翻译）：`symbio_core::vdfs::host`
//! - 地址规则与两半分流（**唯一的翻译点**）：本插件的 `fs` 模块
//! - 物理文件层（磁盘读写 + 路径守卫）：本插件的 `physical` 模块
//! - 线路信封（`vdfs/*` 请求响应 + 协议路径）：本插件的 `protocol` 模块
//! - 访问层（取根 / 翻译操作 / 树遍历 / 事件投递）：本插件的 `host` 模块
//! - LLM 工具链路（把工具调用改为对 `UnifiedFs` 的调用）：本插件的 `provider` 模块
//! - 虚拟层拓扑（容器聚合 + 注册为根）：`plugins/composite/vdfs.rs`

