//! work 插件 —— **工作区记忆**（让模型记得住，也改得动）。
//!
//! ## 它解决什么
//!
//! 会话是**一次性**的：模型每开一个新会话都从零开始，用户在上一轮说过的偏好、
//! 项目里已定的约定、反复踩过的坑，全都要再说一遍。本插件给工作区补上一份
//! **跨会话保留**的记忆，并把它**每轮注入**系统提示词。
//!
//! ## 两条腿，缺一不可
//!
//! | 交出什么 | 机制 | 缺了会怎样 |
//! |---|---|---|
//! | 系统提示词 | `CapabilityVisitor::register_system_prompt` | 模型不知道记忆存在，等于没有 |
//! | VDFS 挂载点 `.vdfs/work` | `CapabilityVisitor::register_vdfs_provider` | 只能读不能改，记忆永远长不大 |
//!
//! 两者都在 `traverse(TRAVERSE_AVAILABLE_TOOLS)` 这一次广播里交出——与工具、模型服务、
//! VDFS 挂载点、配置声明**共用同一次收集**，不新增任何收集通道。
//!
//! ## 作用域闸门：**选了工作区才有记忆**
//!
//! `ctx[WORKDIR]` 缺失 / 为空 = 用户没有在工作区上下文里提问 → **什么都不注入**。
//! 这不是优化，是语义：把 A 项目的约定带到 B 项目、或带进一个根本没选工作区的
//! 闲聊会话，都是错的。闸门在 `plugin::WorkPlugin::store_with` 一处收口。
//!
//! ## 为什么走「系统提示词」而不是别的通道
//!
//! 系统提示词只有**一个**注册通道（`register_system_prompt`）：注册的每一段都按
//! 顺序送达模型，不存在「取一个」的竞争，因此记忆不会被别的东西挤掉，也不会去挤
//! 别人。人格的**选择**发生在注册期（model 插件按 `PROVIDER_ID` 解析出唯一生效
//! provider 后才注册），消费侧不参与挑选。
//!
//! ## 落位：工作区根目录的 `AGENTS.md`
//!
//! ```text
//! {workdir}/AGENTS.md                     记忆本体（行业通行约定，随仓库可版本化）
//! {homedir}/plugins/work/PLUGIN.yml       本插件配置（两道闸门开多大）
//! ```
//!
//! 文件名与位置**刻意对齐行业惯例**（`AGENTS.md`：给编码智能体的工作区级指令文件），
//! 于是记忆**不属于 symbio**：换工具照样生效，能被 `git` 版本化、被 review。
//!
//! ## 归属：这一层只归本插件
//!
//! 同一个 `{workdir}/AGENTS.md` 曾经被 session 插件也读一遍（当「工作区指令」注入
//! 系统提示词基座），结果是同一份内容进两次上下文、而模型改不动它。现在的约定是
//! **谁能读写它，谁负责注入它**——一个作用域只有一个所有者。
//!
//! ## 机制在 `symbio_core::memory`，本插件只剩「个性」
//!
//! 工作区 / 会话 / 智能体三层记忆形态相同，共用一份内核实现（读写、两道容量闸门、
//! 片段排版、VDFS 节点）。本插件负责的只有：**落位、地址、标题、空内容提示、
//! 两道闸门开多大**。因此这里不再有第二份「超限怎么办」「截断怎么算」。
//!
//! ## 文件
//!
//! - [`config`]：配置结构（三个字段 = 注不注 / 能写多大 / 每轮背多少）
//! - [`memory`]：落位、VDFS 地址、片段规格（本层的个性）
//! - [`plugin`]：插件本体（`Plugin` 实现 + 作用域闸门收口处）
//! - [`vdfs`]：VDFS 挂载点（`VdfsProvider` 实现）

