//! fact_log 插件 —— **可选的事实日志**：把各域的事实聚合成一条可查询的只读序列。
//!
//! ## 它解决什么
//!
//! 现行体系里，"发生过什么"散在各域的私有存储里：会话在 `messages.json`、资源在
//! VDFS、未来记忆在它自己的文件。新能力（检索者、巩固者、审计者）想知道"哪些事实
//! 发生过"，只能去读别人的存储——**那就产生了插件间依赖**，违反本仓的基本原则。
//!
//! 本插件把这件事变成**一条可选的服务**：它派生事实、登记事实，消费方经
//! [`symbio_core::FactSource`] 取用，谁也不必认识谁。
//!
//! ## 三条设计边界
//!
//! | 边界 | 为什么 |
//! |---|---|
//! | **可选**：停用/未装配 = 系统照常运行（J2 平凡值） | 它提供的是**增强**，不是地基 |
//! | **只读**：只派生 [`Fact`]，不写任何域 | 杜绝"第二份真相"——写入仍走各域原有路径 |
//! | **零插件依赖**：只读磁盘上的**公开布局**，不 import 任何插件 | 插件独立原则（`plugins/mod.rs`） |
//!
//! ## 事实从哪来
//!
//! 本插件**不订阅**任何运行时事件，而是**从磁盘派生**：会话目录的布局是公开约定
//! （`<homedir>/session/<id>/{session.json,messages.json}`，见 `docs/design/vdfs.md`
//! 与 `session` 的 store 模块文档），因此本插件只依赖**约定**，不依赖 `session` 的代码。
//! 这带来一个直接好处：**派生是纯的**——同一份磁盘 → 同一串事实（`seq` 确定），
//! 因此可双跑比对（断言 A4）。
//!
//! > **未来演化**：当记忆（S06）、承诺（S08）等域出现时，它们各自把事实暴露为
//! > 一个 `FactSource` 并登记（经 `CapabilityVisitor::register_fact_source`），
//! > 本插件即可**零改动**地聚合它们——因为契约在 core，不在插件之间。
//!
//! ## 文件
//!
//! - [`config`]：配置结构（能不能派生 / 派生多少）
//! - [`derive`]：从磁盘派生事实的纯函数（本插件的全部机制）
//! - [`plugin`]：插件本体（`Plugin` 实现 + 事实源登记）

