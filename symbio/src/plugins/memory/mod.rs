//! memory 插件 —— **记忆**：智能体自身的 + 工作区的（让模型记得住，也改得动）。
//!
//! ## 它解决什么
//!
//! 会话是一次性的，而有些东西**跨会话成立**。这里管两个作用域：
//!
//! - **智能体自身**：「这个智能体自己」长期成立的事——它是谁、它必须坚持什么、
//!   它踩过什么坑；
//! - **工作区**：「这个项目里长期成立的事」——用户偏好、项目约定、已定结论。
//!
//! 两者物理文件同名（`AGENTS.md`，行业通行约定）但**作用域不同**——放在哪个目录
//! 下就属于哪个作用域；挂载里的名字因此不同（`AGENTS.md` / `WORKSPACE.md`）。
//!
//! ## 智能体腿：一个插件，两个实例（分形）
//!
//! 本插件**不认识**「系统智能体」与「子智能体」这两个词。它只认一条规则：
//!
//! > 智能体记忆文件 = **本插件目录的父目录**下的 `AGENTS.md`。
//!
//! 容器把插件并列在它所属的智能体目录下，于是同一个实现自动得到两个装配作用域：
//!
//! | 实例 | 本插件目录 | 父目录 = 宿主目录 | 记忆文件 | 生效范围 |
//! |---|---|---|---|---|
//! | 系统树 | `<homedir>/memory` | `<homedir>` | `{homedir}/AGENTS.md` | 所有会话 |
//! | 子树 | `<agentdir>/memory` | `<agentdir>` | `<agentdir>/AGENTS.md` | 选中该智能体时 |
//!
//! 子树那份**随 agent 目录整包分发**——它是智能体的资产，不是宿主的私有数据。
//! 正因如此它必须由**子树里那个实例**读写：只有它的父目录是对的。
//! 从前这两份由 `agent` 插件用两个模块（`instruction` / `memory`）各管一个，
//! 落位规则相同却写成两份；现在它们就是同一个插件的两个实例。
//!
//! ## 工作区腿：作用域来自会话（`ctx[WORKDIR]`，可选）
//!
//! 工作区记忆的物理文件是 `{workdir}/AGENTS.md`，作用域来自**会话级选择**：
//! 没选工作区就没有这一腿（不注入、列表缺席），这与智能体腿不同——智能体腿的
//! 作用域来自**装配**，插件被构造出来这件事本身就意味着作用域存在。
//! （这一腿原属独立的 `work` 插件；两个作用域同属「记忆」，收进同一个所有者，
//! 「谁能读写它，谁负责注入它」的原则在插件内一次成立。）
//!
//! ## 两条腿 × 两样交出，缺一不可
//!
//! | 交出什么 | 机制 | 缺了会怎样 |
//! |---|---|---|
//! | 系统提示词（两段） | `CapabilityVisitor::register_system_prompt` | 模型不知道记忆存在，等于没有 |
//! | VDFS 挂载点 `<根>/memory` | `CapabilityVisitor::register_vdfs_provider` | 只能读不能改，记忆永远长不大 |
//!
//! 两者都在 `traverse(TRAVERSE_AVAILABLE_TOOLS)` 这一次广播里交出——与工具、模型服务、
//! VDFS 挂载点、配置声明**共用同一次收集**，不新增任何收集通道。
//!
//! ## 归属：一个作用域只有一个所有者
//!
//! **谁能读写它，谁负责注入它。** 本插件同时给出读写面（`<根>/memory/…`）
//! 与注入面，因此印在片段里的地址与闸门都是**它自己会执行**的。
//! 子树的注册经 `agent` 插件的 `SubAgentVisitor` 加 `agent/<id>/` 前缀，
//! 与系统侧**并集**且不撞名。
//!
//! ## 机制在 `providers/memory`，本插件只剩「个性」
//!
//! 工作区 / 会话 / 智能体几层记忆形态相同，共用一份实现（读写、两道容量闸门、
//! 片段排版、VDFS 节点）。本插件负责的只有：**落位、地址、标题、空内容提示、
//! 两道闸门开多大**。因此这里不再有第二份「超限怎么办」「截断怎么算」。
//!
//! ## 文件
//!
//! - [`config`]：配置结构（两个作用域各一组闸门 + 工作区注入开关）
//! - [`memory`]：智能体腿的落位、VDFS 地址、片段规格（本层的个性）
//! - [`workspace`]：工作区腿的落位、挂载名、片段规格（本层的个性）
//! - [`plugin`]：插件本体（`Plugin` 实现 + 工作区作用域闸门收口处）
//! - [`vdfs`]：VDFS 挂载点（`VdfsProvider` 实现）

