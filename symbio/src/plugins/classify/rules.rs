//! 反射档规则表 —— 问候 / 致谢 / 确认 / 空输入，**纯查表，零 LLM 往返**。
//!
//! ## 为什么需要它（G-C）
//!
//! 「你好」「谢谢」「好的」这类输入不该付一次快速档分类往返——它们不是需要
//! 理解意图的话，是**礼节**。plan 的反射档（80ms）正是为此留的位置。
//!
//! ## 一条硬判据：**全等**匹配，不是包含
//!
//! 归一化后要求**逐字全等**。理由不是洁癖，是失败方向：
//!
//! - 若用**包含**匹配，「你好，帮我读一下 README」会被判成问候 ⇒ 走 `Answered`
//!   ⇒ **用户真正的请求被静默吞掉**（本轮不进工具循环，也没人干活）。
//!   这是最坏的一类错误：它不报错、不告警，只表现为「助手没理我」。
//! - 全等匹配漏掉的只是「谢谢啦」「多谢您」这类**变体**——它们落到快速档，
//!   多付一次分类往返，**功能完整**。
//!
//! 漏判的代价是慢一点，误判的代价是丢请求。表是数据，加一行就能补漏判；
//! 误判没有这样的出口。
//!
//! ## 为什么表在插件里而不是配置里
//!
//! 表是**代码级常量**：它要被单测逐条钉住（`rules.test.rs`），也要能被审计
//! 脚本看见。放进 `PLUGIN.yml` 会让它变成「运行时数据」——那既失去编译期检查，
//! 又让「哪几条算问候」成为一个无人 review 的运维事实。要改表就改这个文件，
//! 它只有一屏。

use crate::symbio_core::{REASON_ACK, REASON_EMPTY, REASON_GREETING, REASON_THANKS};

/// 归一化时要剥掉的边缘字符（中英标点 + 空白）。
///
/// 只剥**边缘**：内部标点保留，否则「谢谢，不用了」会被归成「谢谢不用了」——
/// 那是一条真实的补充说明，不该落进反射档。
const TRIM_CHARS: &str = " \t\r\n\u{3000}。！？，、；：～·!?,;:.~\"'“”‘’（）()【】[]<>《》";

/// 规则表：`(理由码, 归一化后逐字全等的输入集合)`
///
/// 同一理由码的多条写法只是**数据**——加一条不必碰任何机制。
const TABLE: &[(&str, &[&str])] = &[
    (
        REASON_GREETING,
        &[
            "你好",
            "您好",
            "你好呀",
            "您好呀",
            "大家好",
            "哈喽",
            "嗨",
            "在吗",
            "在么",
            "hi",
            "hello",
            "hey",
            "早上好",
            "早安",
            "中午好",
            "午安",
            "下午好",
            "晚上好",
            "晚安",
        ],
    ),
    (
        REASON_THANKS,
        &[
            "谢谢",
            "谢谢你",
            "谢谢啦",
            "多谢",
            "多谢了",
            "感谢",
            "感谢你",
            "辛苦了",
            "辛苦啦",
            "thanks",
            "thank you",
            "thx",
            "3q",
        ],
    ),
    (
        REASON_ACK,
        &[
            "好",
            "好的",
            "好嘞",
            "行",
            "可以",
            "没问题",
            "嗯",
            "嗯嗯",
            "收到",
            "明白",
            "明白了",
            "了解",
            "知道了",
            "是的",
            "对的",
            "ok",
            "okay",
            "got it",
        ],
    ),
];

/// 归一化：小写 + 剥掉首尾标点与空白。
fn normalize(raw: &str) -> String {
    raw.to_lowercase()
        .trim_matches(|c: char| TRIM_CHARS.contains(c))
        .to_string()
}

/// 规则表判决。命中返回理由码；未命中返回 `None`（⇒ 调用方落快速档）。
///
/// 纯函数：无 I/O、无状态、无 async——它的全部行为都能被 `rules.test.rs` 穷举。
pub(crate) fn classify_by_rule(utterance: &str) -> Option<&'static str> {
    let normalized = normalize(utterance);
    // 空输入（空串 / 纯空白 / 纯标点）没有可理解的内容，但也不是"要干活"：
    // 它是「用户什么都没说」，交给措辞侧决定怎么提示。
    if normalized.is_empty() {
        return Some(REASON_EMPTY);
    }
    TABLE
        .iter()
        .find(|(_, patterns)| patterns.contains(&normalized.as_str()))
        .map(|(reason, _)| *reason)
}

