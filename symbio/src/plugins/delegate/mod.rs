//! delegate 插件 —— **可选的委派者**：主会话与后台 worker 会话之间的三项只读事实。
//!
//! ## 它是谁、为什么存在
//!
//! 目标形态（`docs/plan/06` §10.2）：**主会话只与用户对话**，深度思考与多轮工具在
//! **worker 会话**里做（后者已有先例：`agent/host/subagent.rs` 的 `agent_run`）。
//! 主会话因此**不持有工具**，它要能工作只剩三件事需要外部事实：
//!
//! | 问题 | 本插件给的答案 | 形态 |
//! |---|---|---|
//! | 这轮该不该开一个 worker？ | [`decide`] 的规则判定（前缀 / 关键词 / 长度） | **纯函数** |
//! | 我有哪些能力？（没有工具时靠什么知道） | [`digest`] 把能力清单折成一段目录 | **纯函数** |
//! | 用户问"进展如何"，我拿什么回答？ | [`progress`] 读 worker 会话推出状态快照 | **纯函数 + 磁盘公开布局** |
//!
//! 三者都是**只读事实**：本插件不启动 worker、不写任何域、不认识 `session`。
//!
//! ## 为什么叫 `delegate` 而不叫 `worker`
//!
//! `worker/` 在本仓已是**路由前缀别名**（`worker/session/chat/send` ≡
//! `session/chat/send`，见 `docs/reference/ROUTES.md`）。再用同名插件，会出现
//! 「同名异物」——排查时按名字找代码会找错东西（`docs/plan/06` §1.1 记的正是这
//! 类事故）。`delegate` 说的是本插件的**动作**：判定是否把活委派出去。
//!
//! ## 三条设计边界（与前三个桥接插件同款）
//!
//! | 边界 | 为什么 |
//! |---|---|
//! | **可选**：停用 / 未装配 = 系统照常运行（J2） | 它给的是**事实**，不是地基；不在系统默认装配清单里 |
//! | **只读**：不启动 worker、不写任何域 | 写入仍走各域原有路径（杜绝"第二份真相"） |
//! | **零插件依赖**：只读磁盘公开布局，不 import 任何兄弟插件 | 插件独立原则（`plugins/mod.rs`） |
//!
//! ## 本轮交付的与没交付的
//!
//! 交付：三件事实的**唯一真源**（纯函数 + 两条只读路由）。
//! 未交付（下一步 R1-a）：把它们**注入主会话提示词**——注入点必须是
//! `session::chat_loop::prepare_turn_inputs`（收集完成之后），**不能**是插件的
//! `traverse`：`composite.traverse` 遍历的是 `HashMap`（顺序不定），在 traverse 期
//! 算能力目录会**静默不完整**（J3 意义上的静默失效）。
//!
//! ## 文件
//!
//! - [`config`]：配置（开关 / 前缀 / 关键词 / 长度阈值）
//! - [`decide`]：委派判定（纯函数）
//! - [`digest`]：能力目录折叠（纯函数）
//! - [`progress`]：worker 会话状态快照（纯函数 + 磁盘读）

