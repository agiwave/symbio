//! setting 插件 —— **本智能体自身的信息设置**（我是谁，以及我默认怎么说话）。
//!
//! ## 它解决什么
//!
//! `memory` 记的是「这个智能体**记得**什么」，`setting` 记的是「这个智能体
//! **是**什么」——它的自述（显示名 / 简介）与它回答时的偏好（语言 / 详略）。
//! 两者都是**跨会话生效**、都要能被模型看到，也都必须由用户改得动。
//!
//! ## 与 `memory`（`AGENTS.md`）的分工
//!
//! | | `setting` | `memory` |
//! |---|---|---|
//! | 内容 | 自述与偏好（结构化字段） | 长期事实与约定（自由文本） |
//! | 形态 | 一份配置文档（`PLUGIN.yml`，表单编辑） | 一个文本文件（`AGENTS.md`，正文编辑） |
//! | 谁写 | 人（在设置页填字段） | 人与模型（模型自己按地址读写） |
//!
//! 刻意不合并：把「名字 / 简介」塞进自由文本会让它们没有稳定位置（模型每轮改写
//! 正文时可能顺手改掉），而偏好这种**枚举型**选择用表单比用散文可靠。
//!
//! ## 与 `manifest.yaml` 的分工（子智能体）
//!
//! 子智能体目录里已经有一份 `manifest.yaml`（`id` / `name` / `description` /
//! `version` / 兼容门槛）。它俩不冲突：
//!
//! - **`manifest.yaml` 是接入契约**：随包分发、导入即校验、宿主不改——它回答
//!   「这个包是谁、能不能挂上来」（`agent` 插件的门槛，见
//!   `docs/design/agent-directory-spec.md` §5 / §10）；
//! - **`setting` 是本实例的自述与偏好**：运行期可改、不参与接入判定。
//!
//! ## 一个插件，两个实例：**分形**
//!
//! 与 `memory` 同一条规则——本插件不认识「系统」与「子智能体」：它被装配在哪个
//! 智能体目录下，就描述**那个智能体**。系统树实例读 `<homedir>/setting/PLUGIN.yml`，
//! 子树实例读 `<agentdir>/setting/PLUGIN.yml`。
//!
//! ## 为什么这些字段**都**进系统提示词
//!
//! 本插件没有任何别的消费者：字段若只落盘不进提示词，就是没有消费者的死配置——
//! 「我叫什么」「我说什么语言」只有被模型读到才有意义。因此
//! [`segment`] 把已填写的字段拼成一段【本智能体】注入；**全空则不注入**
//! （缺省状态不改变任何一轮的提示词）。
//!
//! ## 文件
//!
//! - [`config`]：字段结构与表单定义（档案 / 偏好两组）
//! - [`segment`]：字段 → 系统提示词片段
//! - [`plugin`]：插件本体（`PluginConfigMount` 提供挂载点，`traverse` 注入片段）

