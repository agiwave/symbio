/**
 * 服务层失败口径 —— 读/列类服务的唯一收敛点
 *
 * ## 两种口径，只有两种
 *
 * 服务层调用后端（`callPlugin`）失败时，只有两种**合法**处置，二者按
 * 「这次失败是否让调用方无法继续」划分：
 *
 * | 口径 | 适用 | 形态 | 调用方看到 |
 * |---|---|---|---|
 * | **吞错返兜底** | 读 / 列 / 订阅类 | `withFallback(op, fallback, log)` | 一个**形状合法**的空值，页面照常渲染 |
 * | **直抛** | 写 / 动作类 | 裸 `await callPlugin(...)`，不包 try | 异常（含字段级校验信息） |
 *
 * 分界线是**语义**而不是「重不重要」：列表拉不到时页面仍有意义（空目录），
 * 而写入失败必须让用户知道（否则会以为存下了）。写类若也吞错，用户会看到
 * 一个"成功"的假象——这正是最坏的一种失败。
 *
 * ## 为什么要有一个原语
 *
 * 从前这 9 处读/列入口各自手写一份 `try/catch → logger → return 兜底`。
 * 形状相同的代码并不等于同一件事：它们**兜底值的语义并不一致**——
 * 有的返「形状合法的空容器」（`{ items: [] }`，页面照常渲染），有的返 `null`
 * （调用方必须自己分支）。调用方光看签名看不出自己拿到的是哪一种，只能去读实现。
 *
 * 收敛到一个具名原语之后：
 *
 * 1. **口径可命名、可 grep**——「这里是吞错返兜底」变成调用点一眼可见的事实，
 *    不再是散落的 try/catch 需要逐处辨认；
 * 2. **兜底值必须在调用点写出来**，于是它从"实现的副产品"变成"显式的策略声明"；
 * 3. 日志级别与留痕方式只在这一处决定，不会有的 `error` 有的 `debug` 却没人说得清为什么。
 *
 * 这是**质量**收益，不是行数收益：每处省下的两三行是副产品，真正的价值是
 * 「失败时发生什么」从 9 个互不知情的地方收成 1 条可陈述的规则。
 *
 * ## 不适用本原语的 catch
 *
 * 传输层（`plugin.ts`）与事件总线（`eventBus.ts`）内部也有 catch，但它们**不是**
 * 服务层口径：前者是协议违规/清理路径（含一处 **清理后 rethrow**），后者是
 * 「一个订阅者抛错不能拖垮其它订阅者」的隔离。它们的兜底值与调用方语义无关，
 * 因此继续留在原地——**不要为了"统一"把它们也包进来**。
 */

import { logger } from '@/utils/logger'

/**
 * 失败留痕规格。
 *
 * `level` 默认 `'error'`；**预期内的失败**（如 provider 本就没有实时能力、
 * 节点不存在）降为 `'debug'`——它们在正常路径上会发生，用 error 记录会让
 * 日志失去信噪比，反而盖住真正的故障。
 */
export interface FallbackLog {
  /** 日志模块标签，如 `'vdfs-service'` */
  tag: string
  /** 失败的**主谓**描述，不含尾冒号（如 `listVdfs(@vfs/model) failed`） */
  what: string
  level?: 'error' | 'warn' | 'debug'
}

/**
 * 吞错返兜底：执行 `op`，失败则记日志并返回 `fallback()`。
 *
 * `fallback` 是**惰性**的（thunk 而非值）：兜底值常常要由入参算出来
 * （如 `listVdfs` 的空目录要带上 `path`），且正常路径上不该为它做任何计算。
 *
 * 返回类型与 `op` 一致，因此**兜底值必须与成功值同型**——这正是它比手写
 * try/catch 强的地方：类型系统会拦住「兜底返了 `null` 但签名说不会」这类漂移。
 */
export async function withFallback<T>(
  op: () => Promise<T>,
  fallback: () => T,
  log: FallbackLog
): Promise<T> {
  try {
    return await op()
  } catch (err) {
    logger[log.level ?? 'error'](log.tag, `${log.what}:`, err)
    return fallback()
  }
}
