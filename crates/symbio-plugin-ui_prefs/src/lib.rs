//! ui_prefs —— **界面偏好**插件：外观与提示音的后端权威数据。
//!
//! ## 它解决什么
//!
//! 此前「外观」「关于」是 `plugin_manager` 的自有分区，数据在前端 localStorage 里，
//! 后端没有归属——「一切皆插件」的一致性在这里破了一个口子。本插件把那两份真实
//! 用户数据（主题 / 字号 / 提示音）接成一份配置文档 `<根>/ui_prefs/PLUGIN.yml`，
//! 由 `PluginConfigMount` 统一提供读写、校验与落盘。
//!
//! ## 首屏为什么仍用 localStorage
//!
//! `main.ts` 在 `app.mount` 之前同步调用 `useAppearanceStore().apply()` 来防止主题
//! 闪烁 / 白屏；这是一条**同步**路径，不能改成异步 VDFS 读取。因此 localStorage 保留，
//! 但身份从「唯一数据源」降为「首屏快照 + 离线降级」：后端配置读到后覆盖它，之后
//! 双写；后端缺席时（插件未装配 / 读取失败）前端退回首屏快照，功能不残废。
//!
//! ## 「关于」为什么不落盘
//!
//! 关于页没有用户数据：版本来自编译期（`package.json`），描述是硬编码自述，引导按钮
//! 是纯 UI 流程状态。它归在本插件名下只是**节点归属**（由 `plugin_manager` 声明时
//! 指向本插件），正文恒为空；不为「一致」而制造一份没有消费者的数据。
//!
//! ## 文件
//!
//! - [`config`]：字段结构、缺省值与表单/校验定义
//! - [`plugin`]：插件本体与 `PluginConfigMount` 挂载点

