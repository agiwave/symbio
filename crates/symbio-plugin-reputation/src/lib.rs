//! 声誉台账能力包 —— **按主体折叠的承诺守约账**（名册 #22/#28，DE-038 §2/§3）。
//!
//! | 面 | 用在哪 | 谁读 |
//! |---|---|---|
//! | 视图（`ViewDecl` + `shared_views`） | `reputation.ledger`：各主体的 `offered` / `kept` / `broken` / `score` | 本包的淘汰贡献者、`session` 的声誉列 |
//!
//! 一条折叠、两个读者——搬出 `sdk` 之后，两处读的是**同一条算式**：闸门与出口各自算一遍
//! 迟早漂移成「淘汰说这一行负分、面板说它守约」（D-044 的同一个病），而错的若是声誉表，
//! 收回派活权就建立在一份没人复核的数上。
//!
//! 它**只写一种事实**：`commitment.*` 四格的 owner 仍是 `loop`，写方是效果通路与 `agent`
//! 的立约效果；本包自己的写面只有淘汰裁决 `verdict.asserted`（[`crate::elimination`]），
//! 归属按声明 `@principal` 由会话装配解析。`PLUGIN.yml` 里因此仍没有 `shared_events`——
//! 裁决单消费方，名字随本包走。
//!
//! 没有工具、没有路由、没有行为、没有新端口——`kernel` / `sdk` / `loop` / `session` 一行
//! 都不动，两处读者只是把「类型读 core 的折叠」换成「按名字读 owner 的折叠」（`D-221`）。
//!
//! ## 为什么它有 `Plugin` 实现却没有工具与路由
//!
//! 扩展面都走链接期收集，实例不参与任何判断；实例存在只为**挂载**——装配清单按插件目录
//! 挂载，停用插件 ⇒ 实例不构造。`route` 恒 `NotFound`、`traverse` 恒空数组，两者都不是
//! 占位符而是答案（与 `symbio-plugin-cost` 同一形状、同一理由）。
//!
//! ## 只读视图为什么也是一款能力（名册 #22 的判据）
//!
//! 全面拆分判据（DE-025 §5）里「有事实 ∨ 有行为」是**充分**条件不是必要条件：本包两个
//! 条件都不满足，但折叠有独立的算法与口径（配对、as-of、自报不计），那一份知识需要
//! owner——留在 `sdk` 就是留在机制面，而它今天已经有两个按名字读的读者（`D-285`）。
//! 停用本包 ⇒ 这一列读不出来（缺席态 + 一行 warn），淘汰回路按**不淘汰**继续，
//! 那是「少一项能力」的形状，不是「少一层机制」的形状。
//!
//! ## 依赖面
//!
//! `[dependencies]` 只有 `symbio-plugin-api` 与 `serde_json`。`kernel` / `sdk` / `deploy`
//! 一个都不列，也不认识任何兄弟插件（`E-009`）。

