//! Sandbox 插件（横切沙箱机制的实现方 / 发布方 / DE-058）
//!
//! 沙箱是**被调用的执行环境**，不是反过来依赖工具实现。本 crate 做三件事：
//!
//! | 文件 | 职责 |
//! |---|---|
//! | [`engine`] | 沙箱引擎：策略与具名配置（内部数据，不暴露给其它插件） |
//! | [`detail`] | 沙箱档案详情表单定义（前端机制化渲染，不理解沙箱概念） |
//! | [`plugin`] | 收集期发布引擎句柄 + 沙箱档案的 VDFS 通用管理面 |
//!
//! 架构层（`symbio_platform::sdk::sandbox`）只定义接口形状与 ctx 键；工具名、op 常量、黑白名单
//! 规则一律不进 SDK、不进门面的词汇面。本插件因此可独立增删——没有它，会话全放行降级。

mod detail;
mod engine;
mod plugin;
