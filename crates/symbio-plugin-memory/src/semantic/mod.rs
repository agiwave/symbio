//! 语义记忆（名册 #3）——本轮召回了什么，落成一条可审计的事实（DE-026 D-264）。
//!
//! ## 它是什么，不是什么
//!
//! 语义记忆在这里**不是一个检索算法**（那在 [`crate::recall`]），而是「这一轮向长期
//! 记忆问过什么、拿到了什么」这件事本身：读数由检索面产出，本模块只把它落成一格
//! `memory.recalled`。两者分工就是 DE-036 §6 验收 2 的两半——
//!
//! ```text
//! recall（包内）  ──算出读数（degraded + 有序条目）──▶ 值
//! semantic（包内）──把读数誊成事实（found / top / degraded）──▶ 草稿
//! 宿主            ──收束时按 (prio, owner) 询问、落格──▶ 事实源
//! ```
//!
//! ## 为什么它是一条**收束贡献**而不是环上的债
//!
//! 「本轮有没有召回」不是一定能答成「有」的：答话轮不建召回视图（`Settling.recall`
//! 为 `None`）、一轮可能一条活记忆都没有。写成债就得给这一行编一个「天然空转」的
//! `owes`，环会在同一个债上反复选中它直到步数上界（DE-025 D-250 的同一条理由）。
//!
//! ## 读数从哪里来
//!
//! 宿主在收束时把**摘除之后的读数**作为值交进来（`Settling.recall`，D-264 第 2 条），
//! 本模块不重算折叠——重算就是一轮两个时刻两套读数，而「这一轮模型看见了什么」只有
//! 一个答案。
//!
//! ## 落点为什么在本包（而不是留控制面）
//!
//! 这条事实的**词汇**是记忆的（`memory × asserted` 格、三个读数都是检索语汇），
//! 而它今天**没有第二个读方**（校准自 D-262 起读 `memory.calibrated`）⇒ 不是共同
//! 读面 ⇒ 格位随写方走（D-263 第 2 条的反面分支，D-264 第 4 条）。留在控制面，
//! 每加一个记忆侧读数就要改一次控制面。

