//! memory 插件 —— **记忆**：智能体自身的 + 工作区的 + 本会话的（让模型记得住，也改得动）。
//!
//! ## 它解决什么
//!
//! 会话是一次性的，而有些东西**跨会话成立**；本会话自己也有不许被压缩淘汰的置顶约定。
//! 这里管三个作用域（D-513）：
//!
//! - **智能体自身**（`agent_dir`）：「这个智能体自己」长期成立的事——它是谁、它
//!   必须坚持什么、它踩过什么坑；
//! - **工作区**（`work_dir`）：「这个项目里长期成立的事」——用户偏好、项目约定、已定结论；
//! - **会话**（`session_dir`）：「本会话钉住的事」——不会被上下文水位冲掉的结论与约束。
//!
//! 三层物理文件**统一叫 `MEMORY.md`**（放在哪个目录下就属于哪一层）；挂载名各自
//! 点明作用域：`MEMORY.md` / `WORKSPACE.md` / `SESSION.md`。
//! ⚠️ 稳定指令 / 人格（`AGENTS.md`）不在这里——归 `setting` 插件只读注入（D-527）。
//!
//! ## 智能体腿：一个插件，两个实例（分形）
//!
//! 本插件**不认识**「系统智能体」与「子智能体」这两个词。它只认一条规则：
//!
//! > 智能体记忆文件 = **本插件目录的父目录**下的 `MEMORY.md`。
//!
//! 容器把插件并列在它所属的智能体目录下，于是同一个实现自动得到两个装配作用域：
//!
//! | 实例 | 本插件目录 | 父目录 = 宿主目录 | 记忆文件 | 生效范围 |
//! |---|---|---|---|---|
//! | 系统树 | `<homedir>/memory` | `<homedir>` | `{homedir}/MEMORY.md` | 所有会话 |
//! | 子树 | `<agentdir>/memory` | `<agentdir>` | `<agentdir>/MEMORY.md` | 选中该智能体时 |
//!
//! 子树那份**随 agent 目录整包分发**——它是智能体的资产，不是宿主的私有数据。
//! 正因如此它必须由**子树里那个实例**读写：只有它的父目录是对的。
//! 从前这两份由 owner 插件用两个模块各管一个，
//! 落位规则相同却写成两份；现在它们就是同一个插件的两个实例。
//!
//! ## 工作区腿与会话腿：作用域来自会话上下文（`ctx[WORKDIR]` / `ctx[SESSION_DIR]`）
//!
//! 工作区记忆的物理文件是 `{work_dir}/MEMORY.md`，会话记忆是
//! `{session_dir}/MEMORY.md`。两者都是可选作用域：没选工作区 / 没有会话目录就
//! 没有对应那一腿（不注入、列表缺席）；智能体腿则来自**装配**，插件被构造出来
//! 这件事本身就意味着作用域存在。`session_dir` 由会话上下文按值递来，本插件不从
//! `SESSION_ID` 拼路径，也不拿它开事实源（D-513）。
//!
//! ## 三条腿 × 两样交出，缺一不可
//!
//! | 交出什么 | 机制 | 缺了会怎样 |
//! |---|---|---|
//! | 系统提示词（三段） | `put(CapabilityRow::prompt(…))` | 模型不知道记忆存在，等于没有 |
//! | VDFS 挂载点 `<根>/memory` | `impl VdfsProvider`（容器据此派生挂载行） | 只能读不能改，记忆永远长不大 |
//!
//! 两者都在 `traverse(TRAVERSE_AVAILABLE_TOOLS)` 这一次广播里交出——与工具、模型服务、
//! VDFS 挂载点、配置声明**共用同一次收集**，不新增任何收集通道。
//!
//! ## 归属：一个作用域只有一个所有者
//!
//! **谁能读写它，谁负责注入它。** 本插件同时给出读写面（`<根>/memory/…`）
//! 与注入面，因此印在片段里的地址与闸门都是**它自己会执行**的。
//! 子树的注册经作用域访问器加 `agent/<id>/` 前缀，
//! 与系统侧**并集**且不撞名。
//!
//! ## 机制在 `memory_file`，本插件只剩「个性」
//!
//! 工作区 / 会话 / 智能体几层记忆形态相同，共用一份实现（读写、两道容量闸门、
//! 片段排版、VDFS 节点）。本插件负责的只有：**落位、地址、标题、空内容提示、
//! 两道闸门开多大**。因此这里不再有第二份「超限怎么办」「截断怎么算」。
//!
//! ## 文件
//!
//! - [`config`]：配置结构（三个作用域各一组闸门 + 工作区注入开关）
//! - [`memory`]：智能体腿的落位、VDFS 地址、片段规格（本层的个性）
//! - [`workspace`]：工作区腿的落位、挂载名、片段规格（本层的个性）
//! - [`session`]：会话腿的落位、挂载名、片段规格（本层的个性）
//! - [`plugin`]：插件本体（`Plugin` 实现 + 工作区作用域闸门收口处）
//! - [`vdfs`]：VDFS 挂载点（`VdfsProvider` 实现）
//! - [`episodic`]：**事件形态**的记忆——轮末两条编码（经验 / 判断）经收束贡献落格
//!   （名册第 2 行，DE-026 D-263）。它与上面两腿是同一个所有者的第三种载体：
//!   文件形态能被人手改，事件形态只能被轮末写，两者都叫「记忆」，不该有两个 crate。
//! - [`recall`]：**检索**（名册第 6 行，DE-026 D-264）——轮首检索面（`Retriever`）、
//!   活集折叠与它的声明视图 `memory.live`、召回段的排版与 provider。它读的是
//!   `episodic` 落下的格子：同一份记忆的写与读在同一个所有者手里。
//! - [`semantic`]：**语义记忆**（名册第 3 行，DE-026 D-264）——本轮检索读数落成一格
//!   `memory.recalled` 的收束贡献，外加这条事实的名字与格位。它不重算折叠：读数由
//!   [`recall`] 产出、由宿主作为值交进来（`Settling.recall`）。
//! - [`decl`]：本插件交出的全部声明（一个 owner 一次提交，三个能力模块各交几张）。
//! - [`consolidate`]：**巩固**的写口（D-268 订正）——活集最旧两条的合并与两条
//!   `memory.forgotten`；它的格位是债，不是事件。
//! - [`debt`]：巩固债的申报方（`memory-consolidate` 行，身份从活集派生）。
//! - [`port`]：`memory` 端口的执行体（巩固债在这里被还）。

