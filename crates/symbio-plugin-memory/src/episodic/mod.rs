//! 情景记忆（名册第 2 行）：轮末把「用户说了什么、智能体答了什么」编成至多两条
//! `memory.encoded`（经验 / 判断）。
//!
//! ## 为什么住这里，而不是另起一个 crate
//!
//! 记忆是**一个所有者**：文件形态（`AGENTS.md` / `WORKSPACE.md`）与事件形态
//! （`memory.encoded`）读的是同一件事——「这个智能体 / 这个项目长期成立的东西」，
//! 只是载体不同（一个能被人手改，一个只能被轮末写）。拆成两个 crate 会让
//! 「谁能读写它，谁负责注入它」这条归属原则在插件内失效：两个插件都声称拥有记忆，
//! 而没有任何一处说得出「记忆到底归谁」。
//!
//! 收进来的成本是零：`symbio-plugin-memory` 本来就以 `sub_agent` 挂载、
//! 本来就随装配清单生效或停用。停用本插件 ⇒ 文件形态与事件形态一起消失，
//! 这是「一个所有者」应有的形状。
//!
//! ## 两个子模块
//!
//! | 模块 | 职责 |
//! |---|---|
//! | [`decl`] | 事实形状（`memory.encoded`）与归宿行 |
//! | [`contributor`] | 收束贡献：两条编码与同文去重 |
//!
//! 读侧（召回、巩固、遗忘）仍在 `crates/symbio-plugin-loop`——那是控制面的
//! 行与投影，名册里另计（#3 / #6 待迁）。

