//! 契约层 —— 插件与宿主共享的**纯形状**（插件 ABI 的稳定半边）。
//!
//! ## 这一层是什么
//!
//! **零运行时状态的形状**：请求 / 出参的结构、闭集枚举、`&str` 常量、纯数据类型。
//! 插件「认识世界与声明自己」需要的全部词汇住这里；宿主「替插件做事」的运行时
//! （总线、watch、登记表、时钟）不住这里——那是 `symbio-sdk` 的服务层，它们的
//! 长期方向是逐条端口化 / 声明化（`D-486` 的普查表与重开条件）。
//!
//! ## 为什么是独立 crate 而不是 sdk 里的一个子模块
//!
//! **依赖清单就是 ABI 的真实重量，模块边界不是编译边界。** 一个 `mod contract`
//! 可以被一行 `use crate::event_bus::EventBus` 静默违反；crate 边界不会——
//! 本 crate 的 `Cargo.toml` 里出现第二个运行时依赖，判据（它的头注）就红了。
//! 这与 `D-258`（依赖面即判据）是同一条哲学在 ABI 上的应用：`symbio-sdk` 的
//! 依赖面回答「宿主机制认哪些词汇」，本 crate 的依赖面回答**「插件 ABI 本身有多重」**。
//!
//! ## 与内核的分工（`D-438` 的尺子不变，地址更细）
//!
//! 内核只装**内核机制读的**语法（`kernel/src/lib.rs` 抬头）；本 crate 装**插件间
//! 共享、内核不读**的纯形状。两层的判据是同一条（依赖方数量 ≥ 2 ∧ 零实现），
//! 差别只在读者：内核机制的签名类型进内核，其余进这里。`D-438` 当年把
//! `PromptMessage` 从内核摘到 sdk，摘的是「内核不读」这一半；`D-486` 把地址
//! 从 sdk 细化到本层——**sdk 从此只有服务层，词汇的住址不再与服务混排**。
//!
//! ## 谁消费本层
//!
//! 插件经门面（`symbio_plugin_api`）取用——门面的契约臂从本层转出（HS-002 的
//! 一部分，基线只许降）；宿主侧（gateway / cli）直接依赖。插件**不直接依赖**
//! 本 crate（HS-001 不变）。
